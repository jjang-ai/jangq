# ── Stale-artifact cleanup (M115, iter 39) ────────────────────────────
# Re-converting into an existing output directory would leave v1
# `.jang.safetensors` shards + `model.jang.index.json` alongside the v2
# files, AND any v2 shards from a different shard count (e.g. previously
# 42 shards, now 38 shards → 4 old shards never overwritten). Memory
# `feedback_model_checklist.md` rule 1 calls this out as a historical
# bloat source ("155 GB junk shipped"). We nuke only KNOWN JANG-output
# filenames so user-added files (README.md, custom notes) stay.

STALE_JANG_ARTIFACT_PATTERNS: list[str] = [
    "*.jang.safetensors",              # v1 shard extension
    "model.jang.index.json",           # v1 index
    "model-*-of-*.safetensors",        # v2 shards (regenerated by writer)
    "model.safetensors.index.json",    # v2 index (regenerated by writer)
    "jang_imatrix.safetensors",        # re-calibrated per-convert
    "jang_config.json",                # re-written by writer
]


def _remove_stale_jang_artifacts(output_path: Path) -> list[str]:
    """Remove stale JANG-output files from a pre-existing output_path.

    Scoped to `STALE_JANG_ARTIFACT_PATTERNS`. Skips files whose name contains
    'NNNNN' (in-progress shard names being written by the current convert run)
    to avoid racing with a concurrent pre-flush pass in the same process.
    """
    removed: list[str] = []
    for pattern in STALE_JANG_ARTIFACT_PATTERNS:
        for stale in output_path.glob(pattern):
            if "NNNNN" in stale.name:
                continue
            try:
                stale.unlink()
                removed.append(stale.name)
            except OSError:
                pass
    return removed


